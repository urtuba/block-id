// Writes the compiled ABI and bytecode of BlockID and of the generated verifier to
// contract-data.js. The protocol tests (block-id-sdk) and the browser demo deploy the
// contracts from this file, so they need no Solidity compiler. Run it after every
// change to a contract:
//   npm run export-contract -w contracts
import { writeFile } from "node:fs/promises";
import hre from "hardhat";

const blockId = await hre.artifacts.readArtifact("BlockID");
const verifier = await hre.artifacts.readArtifact("Groth16Verifier");

const source = `// Generated by scripts/export-contract-data.js from the Hardhat build of
// contracts/BlockID.sol and contracts/IdentityProofVerifier.sol (solc 0.8.37, evm cancun).
// Do not edit by hand. test/contract-data.test.js fails if this file is out of date.
//
// BlockID's constructor takes (verifier address, orchestrator address, minSources).

export const blockIdAbi = ${JSON.stringify(blockId.abi, null, 2)};

export const blockIdBytecode = ${JSON.stringify(blockId.bytecode)};

export const verifierAbi = ${JSON.stringify(verifier.abi, null, 2)};

export const verifierBytecode = ${JSON.stringify(verifier.bytecode)};
`;

await writeFile(new URL("../contract-data.js", import.meta.url), source);
console.log("Wrote contract-data.js");
